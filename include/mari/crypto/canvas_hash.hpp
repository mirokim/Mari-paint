// Mari Paint — 픽셀 스냅샷 해시 (docs/03 2절 "픽셀 스냅샷 해시 **계산**" = Mari 의 몫)
//
// 🔴 경계선: 여기는 **단발 해시**만 만든다. prevHash 를 엮은 체인도, 서명도 없다.
//    체인 봉인·ES256·등급 판정은 Sigan 의 몫이다(docs/03 2절). 이 파일에 `prevHash`
//    라는 이름의 인자가 생기면 그건 설계 위반이다.
//
// ══════════════════════════════════════════════════════════════════════════
//  해시 대상 바이트 순서 규약 (v1) — **이 주석이 정본이다**
//
//  왜 이렇게까지 적나: 나중에 Sigan 웹이 같은 .ora 를 받아 **같은 값을 재계산**해야
//  할 수 있다. 그때 "우리 쪽 숫자가 다른데요"를 피하려면 규약이 코드보다 먼저 있어야
//  한다. 아래를 그대로 구현하면 어느 언어에서든 같은 값이 나온다.
//
//  ── 공통 ───────────────────────────────────────────────────────────────
//   · 다이제스트는 SHA-256, 결과 표기는 **소문자 16진 64자**.
//   · 정수 필드는 전부 **리틀엔디안**이다(캔버스 좌표계와 마찬가지로 한 번 정하고 안 바꾼다).
//     SHA-256 내부의 빅엔디안과 헷갈리지 마라 — 그건 알고리즘 규격이고 이건 입력 형식이다.
//   · 픽셀은 **RGBA8, straight(비프리멀티플라이) 알파**다. 코어 전체 규약과 같다.
//     🔴 프리멀티플라이하지 않는다. 합성 내부에서 잠깐 프리멀티플라이를 쓰더라도
//        해시 입력은 언제나 straight 다.
//   · **알파 0 정규화**: a == 0 인 픽셀은 R,G,B 를 0 으로 눕힌 뒤 해시한다.
//     보이지 않는 RGB 찌꺼기(지우고 남은 색)가 "같아 보이는 그림"의 해시를 흔들지
//     않게 하려는 것이다. 즉 **보이는 것이 같으면 해시가 같다.**
//   · 도메인 접두사가 붙는다 — 캔버스 해시와 레이어 해시가 우연히 같은 값을 낼 수
//     없게 한다. (파일 해시는 반대로 접두사가 **없다**. sha256.hpp 참고.)
//
//  ── 캔버스 해시 canvasHashHex(tree) ────────────────────────────────────
//     [1] "mari-canvas-hash/v1\n"   ASCII 20바이트, 개행 포함
//     [2] width                      LE u32  (캔버스 크기. 레이어 bounds 가 아니다)
//     [3] height                     LE u32
//     [4] 픽셀                        합성 결과를 캔버스 영역 [0,0,w,h) 에서 읽은 것.
//                                    **행 우선**(위 → 아래), 각 행은 **왼 → 오른쪽**,
//                                    픽셀당 4바이트 R,G,B,A. 패딩·stride 없음.
//                                    총 w*h*4 바이트.
//     · 캔버스 밖으로 삐져나간 레이어 픽셀은 **해시에 들어가지 않는다.** 캔버스 해시는
//       "지금 보이는 그림"의 해시다.
//     · 빈 타일(할당 안 된 곳)은 (0,0,0,0) 으로 채워져 들어간다 — 즉 **빈 곳도
//       일관되게 기여한다.** 캔버스 크기가 같으면 입력 길이가 항상 같다.
//     · 구현은 가로 띠(band) 단위로 합성해서 스트리밍한다. 8K 캔버스라고 통짜
//       버퍼를 만들지 않는다.
//
//  ── 레이어 픽셀 해시 layerHashHex(layer) ───────────────────────────────
//     [1] "mari-layer-hash/v1\n"    ASCII 19바이트
//     [2] tileSize                   LE u32 (= 64. 타일 크기가 바뀌면 값이 바뀐다)
//     [3] 기여 타일 레코드 0..N개     아래 순서로 **정렬**해서 이어 붙인다:
//                                      ty 오름차순 → 같으면 tx 오름차순 (부호 있는 비교)
//         · tx                        LE i32 (2의 보수)
//         · ty                        LE i32
//         · 픽셀                       64*64*4 = 16384 바이트, 행 우선·왼→오른쪽
//     [4] 기여 타일 수 N              LE u64 (끝에 붙는다)
//     · 🔴 **빈 타일 처리**: 알파가 전부 0 인 타일은 **기여하지 않는다.**
//       할당돼 있든 아니든 마찬가지다 — 타일 할당은 구현 세부(writable() 이 칠하지도
//       않은 타일을 만들 수 있다)라서 해시에 새면 안 된다.
//       그래서 "빈 레이어"는 타일 0개 + N=0 으로 **언제나 같은 값**이 된다.
//     · 레이어 좌표는 캔버스 좌표계 그대로다. **음수 타일 인덱스도 그대로 실린다** —
//       캔버스 밖 픽셀도 레이어 해시에는 들어간다(캔버스 해시와 다른 점이다).
//     · 🔴 **픽셀만** 해시한다. 이름·불투명도·블렌드 모드·가시성은 섞지 않는다.
//       따라서 그룹 레이어와 빈 래스터 레이어는 같은 값을 낸다(둘 다 픽셀이 없다).
//       메타데이터까지 묶고 싶으면 그건 별도 규약(v2)이지 이 함수가 아니다.
//     · RGBA8 타일맵만 받는다. 마스크(Gray8)는 Unsupported 다 — 추측해서 해시하지 않는다.
// ══════════════════════════════════════════════════════════════════════════
#ifndef MARI_CRYPTO_CANVAS_HASH_HPP
#define MARI_CRYPTO_CANVAS_HASH_HPP

#include <mari/core/layer.hpp>
#include <mari/core/result.hpp>
#include <mari/core/tile.hpp>
#include <mari/core/types.hpp>
#include <mari/crypto/sha256.hpp>

#include <string>

namespace mari::crypto {

/// 규약 버전 태그. 바꾸면 값이 전부 바뀐다 — 바꿀 때는 docs 와 같이 바꾼다.
inline constexpr const char* kCanvasHashDomain = "mari-canvas-hash/v1\n";
inline constexpr const char* kLayerHashDomain = "mari-layer-hash/v1\n";

/// 레이어 트리 합성 결과의 SHA-256(소문자 16진). 위 규약의 "캔버스 해시".
[[nodiscard]] Result<std::string> canvasHashHex(const LayerTree& tree);

/// 레이어 하나의 픽셀 해시. 위 규약의 "레이어 픽셀 해시".
[[nodiscard]] Result<std::string> layerHashHex(const Layer& layer);

/// 타일맵 하나의 픽셀 해시. layerHashHex() 의 알맹이다.
/// 레이어가 아닌 타일맵(예: 임시 버퍼)을 대조할 때 쓴다.
[[nodiscard]] Result<std::string> tileMapHashHex(const TileMap& map);

/// 이미 RGBA8 로 펼쳐 둔 픽셀의 캔버스 해시. 위 [1]~[4] 를 그대로 적용한다.
/// `stride` 는 행 간격(바이트). 0 이면 width*4 로 본다.
/// 합성을 이미 끝낸 버퍼(예: `exportComposite()` 결과)를 다시 합성하지 않으려고 둔다.
[[nodiscard]] Result<std::string> canvasHashHexOfPixels(i32 width, i32 height, const u8* rgba,
                                                        usize stride = 0);

} // namespace mari::crypto

#endif // MARI_CRYPTO_CANVAS_HASH_HPP
